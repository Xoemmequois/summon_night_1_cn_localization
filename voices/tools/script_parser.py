def _instr000A(pc, data):
    old = pc
    pc += 1
    while pc < len(data):
        n = data[pc]
        pc += 1
        if n < 8:
            pc += 1
        elif n < 0x80:
            break
    return pc - old


def _instr0027(pc, data):
    i = 5
    while pc + i < len(data) and data[pc + i] != 0:
        i += 1
    return i + 1


def _instr2028(pc, data):
    a = data[pc + 1] if pc + 1 < len(data) else 0
    return {0: 6, 1: 6, 2: 5, 3: 2, 4: 4, 5: 3, 6: 2, 7: 2}.get(a, 2)


def parse_script(path: Path):
    raw = path.read_bytes()
    data = list(struct.unpack("<%dH" % (len(raw) // 2), raw[: len(raw) // 2 * 2]))[6:]
    out = []
    i = 0
    while i < len(data):
        code = data[i]
        if code == 0x000A:
            n = _instr000A(i, data)
        elif code == 0x2028:
            n = _instr2028(i, data)
        elif code == 0x0027:
            n = _instr0027(i, data)
        else:
            n = PC_OFFSET.get(code, 1)
        n = max(n, 1)
        out.append((i, code, data[i + 1:i + n]))
        i += n
    return out
