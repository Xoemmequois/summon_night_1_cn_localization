def instr000A(pc, data)
  old_pc = pc
  pc = pc + 1
  loop do
    n = data[pc]
    pc += 1
    if n < 8
      pc += 1
    elsif n < 0x80
      break
    end
  end
  return pc - old_pc
end

def instr0027(pc, data)
  i = 5
  loop do
    if data[pc + i] == 0
      i += 1
      break
    end
    break if data.size <= i
    i += 1
  end
  return i
end

def instr2028(pc, data)
  arg = data[pc + 1]
  offset = 2
  case arg
  when 0, 1
    offset = 6
  when 2
    offset = 5
  when 3,6,7
    offset = 2
  when 4
    offset = 4
  when 5
    offset = 3
  else
    puts "Invalid Arg for 2028 #{arg}"
  end
  return offset;
end

def getCommandOffset(pc, data)
  offset = 1
  code = data[pc]
  case code
  when 0x000A
    offset = instr000A(pc, data)
  when 0x2028
    offset = instr2028(pc, data)
  when 0x0027
    offset = instr0027(pc, data)
  else
    offset = $pcOffset[code]
    if offset.nil?
        offset = 1
    end
  end
  return offset
end

class Command
  attr :index, true
  attr :code, true
  attr :params, true

  def initialize(i, c, p)
    @index = i
    @code = c
    @params = p
  end
end

def parse_commands(fn)
  return Enumerator.new do |emitter|
    data = IO.binread(fn).unpack("S!<*")[6..]
    i = 0
    while i < data.length
      offset = getCommandOffset(i, data)
      emitter << Command.new(i, data[i], data[i + 1, offset - 1])
      i += offset
    end
  end
end
